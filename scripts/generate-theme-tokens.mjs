// Single palette source. Generated CSS is loaded in <head>, including when the
// application bundle cannot load. --check detects stale committed output.
import { readFile, writeFile } from 'node:fs/promises';
const palettes = JSON.parse(await readFile('src/themes/palettes.json', 'utf8'));
const geometry = JSON.parse(await readFile('src/themes/geometry.json', 'utf8'));
let css = '/* Generated by scripts/generate-theme-tokens.mjs; edit themes/palettes.json. */\n';
const block = (selector, values, extra = '') => `${selector} {\n${Object.entries(values).map(([k,v])=>`  --${k}: ${v};`).join('\n')}\n${extra}}\n`;
for (const [id, schemes] of Object.entries(palettes)) for (const [scheme, values] of Object.entries(schemes)) {
  const selector = id === 'classic' && scheme === 'light' ? ':root, :root[data-theme-id="classic"][data-scheme="light"]' : `:root[data-theme-id="${id}"][data-scheme="${scheme}"]`;
  css += block(selector, values, `  color-scheme: ${scheme};\n`);
}
// Sample windows show the chosen palette; labels stay on the live surface.
for (const [id, schemes] of Object.entries(palettes)) for (const [scheme, p] of Object.entries(schemes)) {
  css += block(`:root[data-scheme="${scheme}"] .preferences-appearance-${id}`, { 'sample-paper': p.paper, 'sample-sidebar': p.sidebar });
  css += block(`:root[data-theme-id="${id}"] .preferences-appearance-${scheme}`, { 'sample-paper': p.paper, 'sample-sidebar': p.sidebar });
}
css += ':root { --radius-scale: 1; }\n:root, .recording-layout, .preferences-details-example {\n';
for (const n of geometry.steps) css += `  --radius-${n}: min(24px, calc(${n}px * var(--radius-scale)));\n`;
for (const [name, n] of Object.entries(geometry.components)) css += `  --radius-${name}: var(--radius-${n});\n`;
css += '}\n';
const path = 'src/themes/tokens.css';
if (process.argv.includes('--check')) { if (await readFile(path,'utf8') !== css) throw Error('Theme tokens are stale'); }
else await writeFile(path, css);
